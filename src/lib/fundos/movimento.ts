/**
 * **O vocabulário de movimento dos fundos** — o mesmo para todos eles.
 *
 * ⭐ **São duas ideias de vida, não duas intensidades**, e vale para qualquer
 * composição: em `formas`, o que se move são as PEÇAS — as esferas derivam, as
 * dobras ondulam; o que muda é a composição. Em `luz`, as peças ficam
 * exatamente onde estão e o que passeia é a COR dentro delas.
 *
 * ⚠️ Um vocabulário só entre fundos diferentes é o que permite ao catálogo
 * descrever qualquer um deles com as mesmas duas palavras — e a quem escolhe,
 * entender o que vai acontecer antes de ligar.
 */
export type MovimentoDoFundo = "nenhum" | "formas" | "luz";
